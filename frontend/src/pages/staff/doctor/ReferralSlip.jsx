import { useEffect, useRef, useState } from 'react'
import { createPortal } from 'react-dom'
import Icon from '../../../components/Icon'
import { api } from '../../../lib/api'
import { pct } from '../../../lib/format'
import { useApi } from '../../../hooks/useApi'
import { useUIStore } from '../../../store/useUIStore'

const LEVEL_TEXT = { HIGH: 'higher risk', MODERATE: 'moderate risk', LOW: 'lower risk' }
const SEX = { MALE: 'M', FEMALE: 'F' }

// "24 October 2026", the way a paper form is dated
const longDate = (d) => new Date(d).toLocaleDateString('en-PH', { day: 'numeric', month: 'long', year: 'numeric' })

// One "Label: ______" field. A value prints on the line; without one the line is left to fill in by hand.
function F({ label, value, grow, hint }) {
  return (
    <span className={grow ? 'f grow' : 'f'}>
      <b>{label}</b>
      <span className="ln">{value}{hint && <i>{hint}</i>}</span>
    </span>
  )
}
const Row = ({ children }) => <div className="row">{children}</div>

// The referring part, filled from the referral; the patient's full name is written by hand (the app keeps initials only)
function Referring({ s }) {
  const p = s.patient
  const reasons = s.reasons.map((r) => r.text + (r.direction === 'RAISES' ? ' (raises)' : ' (lowers)')).join('; ')
  return (
    <section className="part">
      <h2>REFERRAL FORM</h2>
      <p className="sub">{s.clinic.name} · {s.clinic.sector === 'PUBLIC' ? 'public' : 'private'} YAKAP clinic · {s.city}</p>
      <Row><F label="Date:" value={longDate(s.date)} /><F label="Receiving Hospital:" grow hint="laboratory or hospital doing the uACR" /></Row>
      <Row><F label="Name of Patient:" value={p.initials} grow hint="write the full name by hand" /></Row>
      <Row><F label="Age/ Sex:" value={`${p.age} / ${SEX[p.sex] || p.sex}`} /><F label="Barangay:" value={`${p.barangay}, ${s.city}`} grow /></Row>
      <Row><F label="Nationality:" /><F label="Resident code:" value={s.residentCode || 'none'} /></Row>
      <Row><F label="Vital Signs: PR:" /><F label="RR:" /><F label="Temp:" /></Row>
      <b className="lbl">Readings (YAKAP labs)</b>
      <table>
        <tbody>
          <tr><th>Blood pressure</th><td>{s.bloodPressure.sbp}/{s.bloodPressure.dbp} mmHg</td></tr>
          <tr><th>HbA1c</th><td>{s.hba1cPct.toFixed(1)}%</td></tr>
          <tr><th>Creatinine / eGFR</th><td>{s.creatinineMgDl.toFixed(2)} mg/dL / {s.egfr} mL/min/1.73m² (CKD-EPI 2021)</td></tr>
          <tr><th>Screening estimate</th><td>{pct(s.probability)} chance of uACR ≥30 mg/g ({LEVEL_TEXT[s.riskLevel]}); not a diagnosis</td></tr>
          <tr><th>Main reasons</th><td>{reasons}</td></tr>
        </tbody>
      </table>
      <Row><F label="Physical Exam:" grow /></Row>
      <Row><F label="Impression/Diagnosis:" grow value="For CKD screening (uACR)." /></Row>
      <Row><F label="Medications Given:" grow /></Row>
      <Row><F label="Reason for Referral:" grow value={s.request + (s.doctorNote ? ` Note: ${s.doctorNote}` : '')} /></Row>
      <div className="sig">
        <span className="ln">{s.doctorName}</span>
        <b>Signature over Printed Name of Referring Physician</b>
        <span className="prc">PRC No.: <span className="ln" /></span>
      </div>
    </section>
  )
}

// The return slip: the receiving physician fills it in and the patient brings it back to the YAKAP clinic
function Returning({ s }) {
  const p = s.patient
  const back = s.returnTo.clinic + (s.returnTo.nearestPublicClinic ? ` (or ${s.returnTo.nearestPublicClinic})` : '')
  return (
    <section className="part">
      <h2>REFERRAL FORM</h2>
      <p className="sub">Return slip · please send back to {back}</p>
      <Row><F label="Date:" /><F label="Receiving Hospital:" grow /></Row>
      <Row><F label="Name of Patient:" value={p.initials} grow /></Row>
      <Row><F label="Age/ Sex:" value={`${p.age} / ${SEX[p.sex] || p.sex}`} /><F label="Nationality:" /></Row>
      <Row><F label="Vital Signs: BP:" /><F label="PR:" /><F label="RR:" /><F label="Temp:" /></Row>
      <Row><F label="Pertinent History and Physical Exam:" grow /></Row>
      <Row><F label="uACR result:" hint="mg/g" /><F label="Date tested:" /></Row>
      <Row><F label="Impression and Diagnosis:" grow /></Row>
      <Row><F label="Medications/ Treatment:" grow /></Row>
      <div className="sig">
        <span className="ln" />
        <b>Signature over Printed Name of Receiving Physician</b>
      </div>
      <p className="foot">Generated by NEPHLUX. {s.disclaimer}</p>
    </section>
  )
}

function SlipBody({ s }) {
  return (
    <div className="rf">
      <Referring s={s} />
      <div className="cut" aria-hidden="true"><span>✂ cut here · the patient keeps the lower part for the receiving physician</span></div>
      <Returning s={s} />
    </div>
  )
}

// GET /referrals/:id/slip; printing also records it with POST /referrals/:id/slip-printed
export default function ReferralSlip({ id, onClose }) {
  const notify = useUIStore((s) => s.notify)
  const q = useApi(() => api.referrals.slip(id), [id])
  const [printing, setPrinting] = useState(false)
  const closeBtn = useRef(null), close = useRef(onClose)
  close.current = onClose

  useEffect(() => {
    closeBtn.current?.focus()
    const onKey = (e) => { if (e.key === 'Escape') close.current() }
    document.addEventListener('keydown', onKey)
    return () => document.removeEventListener('keydown', onKey)
  }, [])

  // render the print copy first, then open the print dialog on the next frame
  useEffect(() => {
    if (!printing) return
    const t = requestAnimationFrame(() => {
      window.print()
      setPrinting(false)
      api.referrals.markSlipPrinted(id).then(() => notify('Slip marked as printed'), (e) => notify(e.message))
    })
    return () => cancelAnimationFrame(t)
  }, [printing, id, notify])

  return (
    <div className="modal" role="dialog" aria-modal="true" aria-label="Referral form" onClick={(e) => { if (e.target === e.currentTarget) onClose() }}>
      <div className="sheet">
        {q.error ? <p style={{ color: '#a33' }} role="alert">{q.error.message}</p>
          : q.data ? <SlipBody s={q.data} /> : <p>Loading the referral form…</p>}
        <div className="bar">
          <button ref={closeBtn} className="btn" onClick={onClose}>Close</button>
          <button className="btn primary" disabled={!q.data || printing} onClick={() => setPrinting(true)}><Icon name="print" />Print / save as PDF</button>
        </div>
      </div>
      {printing && q.data && createPortal(<div id="printArea"><SlipBody s={q.data} /></div>, document.body)}
    </div>
  )
}
