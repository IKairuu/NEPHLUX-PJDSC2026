import { useEffect, useRef, useState } from 'react'
import { createPortal } from 'react-dom'
import Icon from '../../../components/Icon'
import { api } from '../../../lib/api'
import { pct } from '../../../lib/format'
import { useApi } from '../../../hooks/useApi'
import { useUIStore } from '../../../store/useUIStore'
import { isoDate } from '../ui'

const LEVEL_TEXT = { HIGH: 'higher risk', MODERATE: 'moderate risk', LOW: 'lower risk' }

function SlipBody({ s }) {
  return (
    <>
      <p style={{ font: '600 10px/1 monospace', letterSpacing: '.12em', color: '#a33', margin: '0 0 8px' }}>SCREENING SUPPORT · NOT A DIAGNOSIS</p>
      <h2>Referral slip: urine albumin-creatinine ratio (uACR) test</h2>
      <p>Date {isoDate(s.date)} · Seen at {s.clinic.name} ({s.clinic.sector.toLowerCase()} YAKAP clinic), {s.city}</p>
      <table>
        <tbody>
          <tr><th>Patient name</th><td>______________________________ <span style={{ fontSize: 11, color: '#666' }}>(write by hand; the app keeps initials only)</span></td></tr>
          <tr><th>Patient</th><td>{s.patient.initials}, {s.patient.age} y, {s.patient.sex}, {s.patient.barangay}, {s.city}</td></tr>
          {s.residentCode && <tr><th>Resident code</th><td>{s.residentCode} (answers confirmed with the patient)</td></tr>}
          <tr><th>BP</th><td>{s.bloodPressure.sbp}/{s.bloodPressure.dbp} mmHg</td></tr>
          <tr><th>HbA1c</th><td>{s.hba1cPct.toFixed(1)}%</td></tr>
          <tr><th>Creatinine / eGFR</th><td>{s.creatinineMgDl.toFixed(2)} mg/dL / {s.egfr} mL/min/1.73m² (CKD-EPI 2021)</td></tr>
          <tr><th>Screening estimate</th><td>{pct(s.probability)} estimated chance of uACR ≥30 mg/g ({LEVEL_TEXT[s.riskLevel]})</td></tr>
        </tbody>
      </table>
      <p><b>Main reasons:</b> {s.reasons.map((r) => r.text + (r.direction === 'RAISES' ? ' ↑' : ' ↓')).join(' · ')}</p>
      <p><b>Request:</b> {s.request}</p>
      {s.doctorNote && <p><b>Doctor's note:</b> {s.doctorNote}</p>}
      <p><b>Bring the result back to:</b> {s.returnTo.clinic}{s.returnTo.nearestPublicClinic && ` (or the nearest public YAKAP clinic, ${s.returnTo.nearestPublicClinic})`}.</p>
      <p style={{ marginTop: 22 }}>Doctor: {s.doctorName} &nbsp; PRC No.: ________ &nbsp; Signature: ________</p>
      <p style={{ fontSize: 11, color: '#666', marginTop: 16 }}>Generated by NEPHLUX. {s.disclaimer}</p>
    </>
  )
}

// GET /referrals/:id/slip; printing also records it with POST /referrals/:id/slip-printed
export default function ReferralSlip({ id, onClose }) {
  const notify = useUIStore((s) => s.notify)
  const q = useApi(() => api.referrals.slip(id), [id])
  const [printing, setPrinting] = useState(false)
  const closeBtn = useRef(null), close = useRef(onClose)
  close.current = onClose

  useEffect(() => {
    closeBtn.current?.focus()
    const onKey = (e) => { if (e.key === 'Escape') close.current() }
    document.addEventListener('keydown', onKey)
    return () => document.removeEventListener('keydown', onKey)
  }, [])

  // render the print copy first, then open the print dialog on the next frame
  useEffect(() => {
    if (!printing) return
    const t = requestAnimationFrame(() => {
      window.print()
      setPrinting(false)
      api.referrals.markSlipPrinted(id).then(() => notify('Slip marked as printed'), (e) => notify(e.message))
    })
    return () => cancelAnimationFrame(t)
  }, [printing, id, notify])

  return (
    <div className="modal" role="dialog" aria-modal="true" aria-label="Referral slip" onClick={(e) => { if (e.target === e.currentTarget) onClose() }}>
      <div className="sheet">
        {q.error ? <p style={{ color: '#a33' }} role="alert">{q.error.message}</p>
          : q.data ? <SlipBody s={q.data} /> : <p>Loading the slip…</p>}
        <div className="bar">
          <button ref={closeBtn} className="btn" onClick={onClose}>Close</button>
          <button className="btn primary" disabled={!q.data || printing} onClick={() => setPrinting(true)}><Icon name="print" />Print / save as PDF</button>
        </div>
      </div>
      {printing && q.data && createPortal(<div id="printArea"><SlipBody s={q.data} /></div>, document.body)}
    </div>
  )
}
